CREATE TABLE sensors (
    id UUID PRIMARY KEY,
    digital_twin_id UUID NOT NULL REFERENCES digital_twins(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(200) NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('VIRTUAL', 'PHYSICAL')),
    location geometry(Point, 4326) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (digital_twin_id, code)
);

CREATE TABLE sensor_capabilities (
    sensor_id UUID NOT NULL REFERENCES sensors(id),
    parameter VARCHAR(10) NOT NULL CHECK (parameter IN ('PM25', 'PM10', 'NO2', 'CO2')),
    PRIMARY KEY (sensor_id, parameter)
);

CREATE FUNCTION enforce_sensor_inside_site() RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM digital_twins t
        JOIN sites s ON s.id = t.site_id
        WHERE t.id = NEW.digital_twin_id AND NOT ST_Covers(s.boundary, NEW.location)
    ) THEN
        RAISE EXCEPTION 'Sensor location must be inside or on its Site boundary';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER sensor_inside_site
BEFORE INSERT OR UPDATE OF digital_twin_id, location ON sensors
FOR EACH ROW EXECUTE FUNCTION enforce_sensor_inside_site();

